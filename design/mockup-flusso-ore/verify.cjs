const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const { pathToFileURL } = require('node:url');

(async () => {
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1450, height: 1050 }, deviceScaleFactor: 1.5 });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const click = action => page.locator(`[data-action="${action}"]`).first().click();
  const shot = file => page.locator('#phone').screenshot({ path: path.join(__dirname, file), animations: 'disabled' });
  const verifyPending = async () => {
    await page.waitForSelector('[data-shift="thu"]');
    assert(await page.locator('[data-action="to-destination"]').isDisabled());
    await page.getByRole('button', { name: 'Modifica orario di Gio 29', exact: true }).click();
    await click('save-time');
    assert(await page.locator('[data-action="to-destination"]').isEnabled());
  };
  try {
    await page.goto(pathToFileURL(path.join(__dirname, 'index.html')).href);
    await click('start-analysis');
    await shot('01-analisi.png');
    await page.waitForSelector('[data-shift="thu"]');
    await shot('02-controllo.png');
    await page.getByRole('button', { name: 'Modifica orario di Gio 29', exact: true }).click();
    assert.deepEqual(await page.locator('.wheel[data-wheel="Minuti"] button').allTextContents(), ['00', '15', '30', '45']);
    await shot('03-conferma-orario.png');
    await click('close-modal');
    assert(await page.locator('[data-action="to-destination"]').isDisabled());
    await verifyPending();
    await click('to-destination');
    assert.equal(await page.locator('.provider-head small').count(), 2);
    assert.equal(await page.locator('#viewer-label').innerText(), 'Google Calendar');
    await page.locator('#viewer-app').selectOption('');
    assert.equal(await page.locator('#viewer-label').innerText(), 'Da scegliere quando apri');
    await page.locator('#viewer-app').selectOption('Google Calendar');
    assert(await page.locator('.caloption[data-id="holidays"]').isDisabled());
    await page.locator('.caloption[data-id="local"]').click();
    assert.equal(await page.locator('.caloption[data-id="local"]').getAttribute('aria-checked'), 'true');
    await page.locator('.caloption[data-id="work"]').click();
    await shot('04-calendari.png');
    await click('calendar-next');
    assert.equal(await page.locator('.confirmrow').count(), 5);
    assert(!/Riposo|X indica riposo/.test(await page.locator('#screen').innerText()));
    await shot('05-riepilogo.png');
    await click('save');
    await page.waitForSelector('#added-count');
    assert.match(await page.locator('#added-count').innerText(), /^5/);
    assert.deepEqual(await page.locator('#screen h2,#screen h3').allTextContents(), ['Aggiunti nel calendario', 'Calendario di destinazione']);
    assert.equal(await page.locator('#screen button').count(), 0);
    await shot('06-conclusione.png');
    await click('repeat');
    await verifyPending();
    await click('to-destination');
    await click('calendar-next');
    await click('save');
    await page.waitForSelector('#added-count');
    assert.match(await page.locator('#added-count').innerText(), /^0/);
    await page.locator('.switcher [data-tab="hours"]').click();
    assert.equal(await page.locator('#hours-total').innerText(), '34 h');
    const positioning = await page.locator('[data-entry="ot1"]').evaluate(card => {
      const c = card.getBoundingClientRect();
      const b = card.querySelector('.buttons').getBoundingClientRect();
      return { right: b.left > c.left + c.width / 2, top: b.top < c.top + 22 };
    });
    assert(positioning.right && positioning.top);
    await shot('07-ore.png');
    await click('open-weeks');
    await page.locator('[data-action="week-draft"][data-index="1"]').click();
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#hours-total').innerText(), '34 h');
    await click('open-weeks');
    await page.locator('[data-action="week-draft"][data-index="4"]').click();
    await shot('08-settimane.png');
    assert.equal(await page.locator('.weekoption[aria-checked="true"] .out').innerText(), '1');
    await click('apply-week');
    assert.equal(await page.locator('#hours-total').innerText(), '34 h');
    await page.getByRole('button', { name: 'Modifica straordinari', exact: true }).click();
    await page.locator('.timefield[data-id="end"]').click();
    await page.locator('.wheel[data-wheel="Ore"] [data-time-value="17"]').click();
    await click('save-time');
    assert.equal(await page.locator('#hours-total').innerText(), '35 h');
    await page.getByRole('button', { name: 'Elimina straordinari', exact: true }).click();
    await page.getByRole('button', { name: 'Annulla', exact: true }).click();
    assert.equal(await page.locator('#hours-total').innerText(), '35 h');
    await page.getByRole('button', { name: 'Elimina straordinari', exact: true }).click();
    await click('confirm-delete');
    assert.equal(await page.locator('#hours-total').innerText(), '32 h');
    await page.locator('.switcher [data-tab="settings"]').click();
    assert.deepEqual(await page.locator('.settingsmenu b').allTextContents(), ['Calendario', 'Sfondo', 'Notifiche', 'Aggiornamenti']);
    assert.equal(await page.locator('.settingsmenu small,.settingsmenu p').count(), 0);
    await shot('09-impostazioni.png');
    await page.locator('[data-action="settings-section"][data-id="calendar"]').click();
    assert(!/riposo|riposi/i.test(await page.locator('#screen').innerText()));
    await click('settings-root');
    await page.locator('[data-action="settings-section"][data-id="background"]').click();
    await page.locator('[data-action="set-theme"][data-id="light"]').click();
    assert.equal(await page.locator('html').getAttribute('data-theme'), 'light');
    await page.setViewportSize({ width: 390, height: 900 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.emulateMedia({ reducedMotion: 'reduce' });
    assert.equal(await page.evaluate(() => matchMedia('(prefers-reduced-motion: reduce)').matches), true);
    assert.deepEqual(errors, []);
    console.log('PASS: flusso completo, verifica obbligatoria, 5 aggiunti e 0 duplicati, calendari, settimane, modifica/cancellazione straordinari, menu, temi e larghezza 390 px.');
  } finally {
    await browser.close();
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
